"""Render a digest (spec 6.3 step 8): HTML plus plain text for email, MarkdownV2 for Telegram.

Everything from the feed or the model is untrusted text: HTML is autoescaped, links are limited
to http(s), Telegram text is escaped for MarkdownV2."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from urllib.parse import quote, urlsplit
from zoneinfo import ZoneInfo

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from ..pipeline import DigestEntry, DigestRun
from ..profile import Profile

TEMPLATES = Path(__file__).resolve().parent
_MD_V2 = re.compile(r"([_*\[\]()~`>#+\-=|{}.!\\])")


@dataclass
class ItemView:
    title: str
    url: str
    source: str
    published: str
    one_line: str
    key_points: list[str]
    why_it_matters: str
    snippet: str
    note: str
    ai: bool
    feedback_up: str = ""
    feedback_down: str = ""


@dataclass
class DigestView:
    heading: str
    date: str
    items: list[ItemView]
    notices: list[str]
    warning_count: int
    model_line: str
    usage_line: str
    extra: dict[str, str] = field(default_factory=dict)


def http_url(url: str) -> str:
    parts = urlsplit(url)
    return url if parts.scheme in {"http", "https"} and parts.hostname else ""


def feedback_url(repo_url: str, item_id: str, vote: str) -> str:
    if not repo_url:
        return ""
    body = quote(f"item:{item_id} vote:{vote}", safe="")
    return f"{repo_url.rstrip('/')}/issues/new?title=feedback&body={body}"


def _item_view(entry: DigestEntry, zone: ZoneInfo, repo_url: str) -> ItemView:
    s = entry.summary
    it = entry.item
    return ItemView(
        title=it.title,
        url=http_url(it.canonical_url),
        source=it.source_id,
        published=it.published_at.astimezone(zone).strftime("%b %d"),
        one_line=s.one_line if s else "",
        key_points=list(s.key_points) if s else [],
        why_it_matters=s.why_it_matters if s else "",
        snippet=entry.fallback_snippet or "",
        note=entry.note,
        ai=s is not None,
        feedback_up=feedback_url(repo_url, it.id, "up"),
        feedback_down=feedback_url(repo_url, it.id, "down"),
    )


def build_view(run: DigestRun, profile: Profile, now: datetime, repo_url: str = "") -> DigestView:
    zone = ZoneInfo(profile.delivery.timezone)
    models = sorted({f"{e.provider}/{e.model}" for e in run.entries if e.summary is not None})
    return DigestView(
        heading="Axon digest",
        date=now.astimezone(zone).strftime("%a %b %d, %Y"),
        items=[_item_view(e, zone, repo_url) for e in run.entries],
        notices=list(run.notices),
        warning_count=len(run.warnings),
        model_line=("Summaries are AI-generated by " + ", ".join(models) + "; verify against "
                    "the source.") if models else "No AI summaries in this digest.",
        usage_line=(
            f"Tokens: {run.usage.prompt_tokens} in, {run.usage.completion_tokens} out "
            f"({run.usage.calls} calls, {run.cache_hits} cached)."
        ),
    )  # fmt: skip


def _md_v2(value: str) -> str:
    return _MD_V2.sub(r"\\\1", value)


def _env() -> Environment:
    env = Environment(
        loader=FileSystemLoader(str(TEMPLATES)),
        autoescape=lambda name: bool(name and name.endswith(".html.j2")),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    env.filters["tg"] = _md_v2
    return env


def render_email(view: DigestView) -> tuple[str, str, str]:
    env = _env()
    subject = f"{view.heading}: {view.date} ({len(view.items)} items)"
    text = env.get_template("email.txt.j2").render(v=view)
    html = env.get_template("email.html.j2").render(v=view)
    return subject, text, html


def render_telegram(view: DigestView) -> str:
    return _env().get_template("telegram.md.j2").render(v=view)
