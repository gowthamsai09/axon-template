from __future__ import annotations

import pytest

from digest.pipeline import DigestEntry, DigestRun
from digest.render import (
    build_view,
    feedback_url,
    http_url,
    render_email,
    render_telegram,
)
from digest.summarizers.base import Summary, Usage
from tests.conftest import NOW, make_profile
from tests.test_rank import mk


def entry(title: str = "A <b>title</b> & more", **over: object) -> DigestEntry:
    summary = Summary(
        status="ok", title="t", one_line="Short one_line.", key_points=["Point <1>", "Point 2"],
        why_it_matters="Matters.", tags=[], entities=[], notable_figures=[],
        source_url="https://example.com/x", injection_flag=False,
    )  # fmt: skip
    base = DigestEntry(mk(title=title), 0.9, summary=summary, provider="deepseek", model="m")
    for k, v in over.items():
        setattr(base, k, v)
    return base


def run_of(*entries: DigestEntry) -> DigestRun:
    return DigestRun(list(entries), usage=Usage(100, 40, 2), cache_hits=1, notices=["a notice"])


def test_email_html_and_text_content() -> None:
    view = build_view(run_of(entry()), make_profile(), NOW, "https://github.com/o/r")
    subject, text, html = render_email(view)
    assert subject == "Axon digest: Tue Oct 20, 2026 (1 items)"
    assert "Short one_line." in text and "Point <1>" in text and "NOTICE: a notice" in text
    assert "AI-generated by deepseek/m" in text and "Tokens: 100 in, 40 out" in text
    assert "Point &lt;1&gt;" in html and "A &lt;b&gt;title&lt;/b&gt; &amp; more" in html
    assert "<b>title</b>" not in html and 'href="https://example.com/x"' in html
    assert "issues/new?title=feedback&amp;body=item%3A" in html


def test_extractive_item_is_labelled_and_has_no_ai_claim() -> None:
    e = entry(
        summary=None,
        fallback_snippet="Just a snippet.",
        note="not AI-summarized (extractive snippet)",
    )
    view = build_view(run_of(e), make_profile(), NOW)
    _, text, html = render_email(view)
    assert "Just a snippet." in text and "not AI-summarized" in html
    assert (
        "No AI summaries in this digest." in text and "&#128077;" not in html
    )  # no repo: no votes


@pytest.mark.parametrize(
    "url", ["javascript:alert(1)", "data:text/html,x", "ftp://x.example/a", ""]
)
def test_unsafe_links_are_dropped(url: str) -> None:
    assert http_url(url) == ""
    assert http_url("https://example.com/a") == "https://example.com/a"


def test_feedback_url_encoding() -> None:
    assert feedback_url("", "abc", "up") == ""
    url = feedback_url("https://github.com/o/r/", "abc", "down")
    assert url == "https://github.com/o/r/issues/new?title=feedback&body=item%3Aabc%20vote%3Adown"


def test_telegram_markdown_v2_escaping() -> None:
    e = entry(title="Release v1.2 (beta) - fast_inference!")
    out = render_telegram(build_view(run_of(e), make_profile(), NOW))
    assert "Release v1\\.2 \\(beta\\) \\- fast\\_inference\\!" in out
    assert "Point <1\\>" in out and "[Release" in out
    assert "Axon digest" in out.splitlines()[0]
